"""Track A: G1 (idle legs) in Gazebo Harmonic + Nav2 + slam_toolbox.

M2a scaffold. Depends on pieces that don't exist in this repo yet:
  - src/g1_description/urdf/g1.urdf.xacro (see its README.md)
  - worlds/ with a world generated by world_from_map.py (see docs/plan.md)
  - src/g1_nav_overlay/config/nav2_standard.yaml adapted to the G1's footprint

This launch file defines the expected orchestration; running it before those
pieces are populated will fail to resolve the xacro/world/config.
"""

import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node


def generate_launch_description():
    world_arg = DeclareLaunchArgument(
        "world",
        default_value="empty.sdf",
        description="World name under worlds/ (generated by world_from_map.py)",
    )
    nav2_params_arg = DeclareLaunchArgument(
        "nav2_params_file",
        default_value=PathJoinSubstitution(
            [
                get_package_share_directory("g1_nav_overlay"),
                "config",
                "nav2_standard.yaml",
            ]
        ),
        description="Nav2 overlay adapted to the G1's footprint",
    )

    description_launch = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(
            os.path.join(
                get_package_share_directory("g1_description"),
                "launch",
                "description.launch.py",
            )
        )
    )

    gz_sim = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(
            PathJoinSubstitution(
                [get_package_share_directory("ros_gz_sim"), "launch", "gz_sim.launch.py"]
            )
        ),
        launch_arguments={"gz_args": LaunchConfiguration("world")}.items(),
    )

    base_bridge = Node(
        package="g1_base_bridge",
        executable="g1_base_bridge",
        name="g1_base_bridge",
        output="screen",
        parameters=[{"backend": "gazebo"}],
    )

    nav2_bringup = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(
            PathJoinSubstitution(
                [get_package_share_directory("nav2_bringup"), "launch", "navigation_launch.py"]
            )
        ),
        launch_arguments={"params_file": LaunchConfiguration("nav2_params_file")}.items(),
    )

    return LaunchDescription(
        [
            world_arg,
            nav2_params_arg,
            description_launch,
            gz_sim,
            base_bridge,
            nav2_bringup,
        ]
    )
